  await page.locator('#scene-search').fill('不存在的光影xyz');
  assert.equal(await page.locator('#gallery-empty').isVisible(), true);
  await page.locator('#reset-filters').click();
  assert.equal(await page.locator('.card:not(.is-hidden)').count(), 48);
  console.log('✓ 搜索、收藏持久化、最近使用、分类内切换与返回位置恢复');

  const denied = await context.newPage();
  await denied.addInitScript(() => Object.defineProperty(navigator, 'xr', { configurable: true, value: {
    isSessionSupported: async () => true,
    requestSession: async () => { throw new DOMException('Denied', 'NotAllowedError'); },
  } }));
  await denied.goto(base, { waitUntil: 'networkidle' });
  await denied.waitForFunction(() => !document.querySelector('#enter-xr').disabled);
  await denied.locator('#enter-xr').click();
